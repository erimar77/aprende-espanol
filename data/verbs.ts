// Helper functions
export function getVerbByInfinitive(infinitive: string): Verb | undefined {
  return allVerbs.find(v => v.infinitive === infinitive);
}

export function getVerbById(id: string): Verb | undefined {
  return allVerbs.find(v => v.id === id);
}

export function getVerbsByType(type: Verb['type']): Verb[] {
  return allVerbs.filter(v => v.type === type);
}

export function searchVerbs(query: string): Verb[] {
  const lowerQuery = query.toLowerCase();
  return allVerbs.filter(
    v =>
      v.infinitive.toLowerCase().includes(lowerQuery) ||
      v.english.toLowerCase().includes(lowerQuery)
  );
}

export function getRandomVerbs(count: number): Verb[] {
  const shuffled = [...allVerbs].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
