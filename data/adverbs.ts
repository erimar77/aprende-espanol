// Helper functions
export function getAdverbsByCategory(category: string): Word[] {
  return adverbs.filter(adv => adv.category === category);
}

export function getAdverbCategories(): string[] {
  return [...new Set(adverbs.map(adv => adv.category))];
}

export function searchAdverbs(query: string): Word[] {
  const lowerQuery = query.toLowerCase();
  return adverbs.filter(
    adv =>
      adv.spanish.toLowerCase().includes(lowerQuery) ||
      adv.english.toLowerCase().includes(lowerQuery)
  );
}

export function getRandomAdverbs(count: number): Word[] {
  const shuffled = [...adverbs].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
