export function getTestQuestions(): TestQuestion[] {
  return [...testQuestions].sort(() => Math.random() - 0.5);
}

export function getQuestionsByCategory(category: string): TestQuestion[] {
  return testQuestions.filter(q => q.category === category);
}

export function calculateScore(answers: Record<string, string>): {
  total: number;
  correct: number;
  percentage: number;
  byCategory: Record<string, { total: number; correct: number }>;
} {
  const byCategory: Record<string, { total: number; correct: number }> = {};
  let correct = 0;

  testQuestions.forEach(q => {
    if (!byCategory[q.category]) {
      byCategory[q.category] = { total: 0, correct: 0 };
    }
    byCategory[q.category].total++;

    if (answers[q.id] === q.correctAnswer) {
      correct++;
      byCategory[q.category].correct++;
    }
  });

  return {
    total: testQuestions.length,
    correct,
    percentage: Math.round((correct / testQuestions.length) * 100),
    byCategory,
  };
}
